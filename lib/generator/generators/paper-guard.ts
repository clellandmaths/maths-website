/**
 * **Never the paper's own question** — the owner's rule, 2026-10-07: "the exam paper question never appears
 * in a draw. This should be for the exact exam paper question, if one thing changes - it can appear in a
 * draw." A teacher sets generated questions as homework, and a pupil who meets the paper's own question can
 * follow its video walkthrough to the answer.
 *
 * `paperQuestionOf` says whether a generated N5 question IS a past paper question. `generateQuestion` draws
 * again when it is (see generator.ts), so a draw that is not a paper question is exactly what it was, and uses
 * no extra randomness.
 *
 * Two tables, in turn:
 * - **the harvest** (`paper-guard-keys.ts`, generated by `scripts/emit-paper-guard.mts`, live since 2026-10-09):
 *   every key the paper questions' disguises produced when every N5 card was drawn, by the owner's "same question"
 *   test (`../same-question.ts`). Keys are hashed, so it is small.
 * - **AH's design for N5** (since 2026-10-16, the owner's "Yes", https://claude.ai/artifact/UWUx2p9MB722HVJ6NjnxBs;
 *   `n5-same-keys.ts`, the table `n5-paper-same.ts` from each paper's own question as its card builds it):
 *   G1 any paper's identities, whichever card drew it (the paper in another card's words, by the owner's rulings);
 *   G3 the draw's OWN paper's parts held by working and answer, under the paper's own figure (the owner's "B": a
 *   part read off a graph is the paper's only on its own graph), half the paper's marks or more, wherever the change
 *   is (a number changed in the opening line that only one part uses leaves the other parts the paper's);
 *   G4 any OTHER paper's parts held word for word, half that paper's marks or more (P2 across cards), parts with
 *   little maths of their own included when they are the paper's numbers (the owner's "Yes", card 4).
 *   AH's one-part-changed rule (its G2) is not used: in N5 a part's data sits in its own line, so it kept a paper's
 *   part from other working (8x + 3y = 24 kept 2014 P1 Q11's (b) answer (3, 0)); G3 compares working and answer.
 */
import { PAPER_GUARD } from './paper-guard-keys';
import { sameQuestionKey, sameWorkingKey, answerFingerprint, shortHash } from '../same-question';
import { identities, sheetPartsOf, wholeAsPart, heldOf, marksHeld, type Q } from './n5-same-keys';
import { PAPER_SAME, PAPER_OWN_PARTS, PAPER_PARTS } from './n5-paper-same';
import { N5_VARIATIONS } from './n5-variations';
import type { GeneratedQuestion } from './types';

const FINGERPRINTS = new Set<string>(PAPER_GUARD.fingerprints);
const KEYS = new Map<string, string>(Object.entries(PAPER_GUARD.keys));
/** Each paper identity to its paper (the table gives each identity to one paper). */
const SAME = new Map(Object.entries(PAPER_SAME).flatMap(([p, ks]) => ks.map(k => [k, p] as const)));
const ACROSS = Object.entries(PAPER_PARTS);
const OWN_PARTS_PAPERS = Object.keys(PAPER_OWN_PARTS);

/** The harvest's verdict. Cheap for nearly every draw: the answer is checked first. */
function harvested(q: Partial<GeneratedQuestion>): string | null {
  const answer = q.finalAnswer ?? '';
  if (!FINGERPRINTS.has(shortHash(answerFingerprint(answer)))) return null;
  const lines = q.questionLines ?? [];
  const byWording = KEYS.get(shortHash(`Q:${sameQuestionKey(lines, answer)}`));
  if (byWording) return byWording;
  const w = sameWorkingKey(lines, answer, q.solutionSteps ?? []);
  return w ? KEYS.get(shortHash(w)) ?? null : null;
}

/** A card's own papers (a lettered citation, "2019 P1 Q5a", is its question's). */
const stem = (p: string) => p.trim().replace(/([a-z])$/, '');
const ownPapers = (card: string | undefined): Set<string> => new Set((card ? N5_VARIATIONS[card]?.basedOn ?? [] : []).map(stem));

/**
 * The paper label a generated question is, or null. `card` is the variation the draw is (an alias's own papers are
 * its own): it names the papers G3 holds the draw's parts against. Without it only the harvest, G1 and G4 apply.
 */
export function paperQuestionOf(q: Partial<GeneratedQuestion>, card?: string): string | null {
  return paperVerdictOf(q, card)?.paper ?? null;
}

/** The live table's verdict alone: for a draw the request throws away anyway (see generator.ts). */
export const harvestedPaperOf = (q: Partial<GeneratedQuestion>): string | null => harvested(q);

/** As `paperQuestionOf`, with the rule that decided it (G0 the harvest, G1.<key>, G3, G3x, G4), for the measurements. */
export function paperVerdictOf(q: Partial<GeneratedQuestion>, card?: string): { paper: string; rule: string } | null {
  const live = harvested(q);
  if (live) return { paper: live, rule: 'G0' };
  const b: Q = {
    questionLines: q.questionLines ?? [], solutionSteps: q.solutionSteps ?? [], stepMarks: q.stepMarks,
    finalAnswer: q.finalAnswer ?? '', variationId: card ?? q.variationId,
  };
  for (const [tag, k] of identities(b)) { const p = SAME.get(k); if (p) return { paper: p, rule: `G1.${tag}` }; }
  const own = ownPapers(card ?? q.variationId);
  let partKeys: Set<string> | undefined;
  const holds = (label: string) => {
    const op = PAPER_OWN_PARTS[label];
    if (!op) return false;
    if (!partKeys) { const w = wholeAsPart(b, true); partKeys = new Set(w ? [w.key] : sheetPartsOf(b, false, true).map(x => x.key)); }
    const have = partKeys;
    return 2 * op.parts.reduce((t, x) => t + (have.has(x.key) ? x.marks : 0), 0) >= op.total;
  };
  for (const label of own) if (holds(label)) return { paper: label, rule: 'G3' };
  // G3 on every other paper too (the owner's "Yes", card 4): a sister card stating a and b for 2023 P1 Q4's own
  // parabola (2 of its 3 marks), a one-part card asking 2025 P1 Q7's (b) — the paper's own numbers and working
  for (const label of OWN_PARTS_PAPERS) if (!own.has(label) && holds(label)) return { paper: label, rule: 'G3x' };
  const held = heldOf(b);
  for (const [paper, x] of ACROSS) {
    if (own.has(paper)) continue;
    const m = marksHeld(x.parts, held);
    if (m > 0 && 2 * m >= x.total) return { paper, rule: 'G4' };
  }
  return null;
}

/** How many draws in a row may be a paper question before the guard gives up loudly (no card comes close). */
export const GUARD_LIMIT = 200;
