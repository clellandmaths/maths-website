/**
 * The permanent public identifier for every Advanced Higher card.
 *
 * A shared worksheet link carries a card's code and a seed, and regenerates
 * the question from the pair, so a code lives as long as the links do. The
 * rule is National 5's (`../variation-codes.ts`), for the same reason:
 *
 * **An entry may be added. It may never be changed or removed.**
 *
 * Each code is `codeFor(id)`, the same five-character hash National 5 uses,
 * unless that spells a word a teacher would not want in a link; then it is the
 * next hash that does not (`__checks__/lib/code-words.ts`, the owner's rule of
 * 2026-10-01). `ah-registry` fails if any code here is not, if a registered card has
 * none, or if a code is also one of National 5's: a link names its course,
 * but a code that meant two questions would be one bad lookup from handing a
 * pupil the wrong one.
 *
 * Add a card's line in the commit that registers it. Do not remove the line
 * of a card whose routine is withdrawn: its code stays taken.
 */
